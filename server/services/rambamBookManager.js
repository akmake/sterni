let booksCache = null;

function loadBooks() {
  if (booksCache) return booksCache;
  try {
    if (existsSync(RAMBAM_DATA_PATH)) {
      booksCache = JSON.parse(readFileSync(RAMBAM_DATA_PATH, 'utf8'));
      return booksCache;
    }
  } catch (err) {
    console.error('[rambam] Failed reading rambamData.json:', err.message);
  }
  return [];
}

/**
 * Returns treatise information matching the Sefaria ref/title
 */
export function findTreatiseInfo(rawRefOrTitle) {
  const books = loadBooks();
  if (!books.length) return null;

  const normalized = String(rawRefOrTitle || '').toLowerCase().replace(/_/g, ' ');

  for (const b of books) {
    for (let tIdx = 0; tIdx < b.treatises.length; tIdx++) {
      const t = b.treatises[tIdx];
      const titleLower = t.title.toLowerCase();
      // Match "Mishneh Torah, Damages to Property"
      if (normalized.includes(titleLower) || titleLower.includes(normalized)) {
        return {
          ...t,
          bookNum: b.bookNum,
          bookTitle: b.bookTitle,
          bookIntro: b.bookIntro,
          isFirstInBook: tIdx === 0,
          isLastInBook: tIdx === b.treatises.length - 1,
        };
      }
    }
  }

  // Fallback: search by Hebrew title
  for (const b of books) {
    for (let tIdx = 0; tIdx < b.treatises.length; tIdx++) {
      const t = b.treatises[tIdx];
      const cleanHe = t.heTitle.replace(/הלכות\s+/, '').trim();
      if (cleanHe && normalized.includes(cleanHe)) {
        return {
          ...t,
          bookNum: b.bookNum,
          bookTitle: b.bookTitle,
          bookIntro: b.bookIntro,
          isFirstInBook: tIdx === 0,
          isLastInBook: tIdx === b.treatises.length - 1,
        };
      }
    }
  }

  return null;
}

